    private static func centre(_ image: CGImage) -> [Int] {
        let data = image.dataProvider!.data! as Data
        let offset = image.height / 2 * image.bytesPerRow + image.width / 2 * 4
        return data[offset..<offset + 3].map(Int.init)
    }

    @Test func picturesComeFromTheSecondAskedFor() async throws {
        let file = FileManager.default.temporaryDirectory.appendingPathComponent("scrub-\(UUID().uuidString).mkv")
        defer { try? FileManager.default.removeItem(at: file) }
        try #require(Data(base64Encoded: Self.clip, options: .ignoreUnknownCharacters)).write(to: file)
        let frames = ScrubFrames()
        // Backwards too: the same open file serves every position.
        for (time, expected) in [(0.5, 0), (4.5, 2), (2.5, 1), (5.9, 2)] {
            let picture = try #require(await frames.picture(url: file.path, at: time))
            let pixel = Self.centre(picture.image)
            #expect(pixel.firstIndex(of: pixel.max()!) == expected, "\(time) s gave \(pixel)")
            #expect(picture.time <= time && picture.time > time - 1.1)
            #expect(picture.image.width == 640 && picture.image.height == 360)
        }
        #expect(await frames.picture(url: "/nowhere.mkv", at: 1) == nil)
        frames.close()
    }
